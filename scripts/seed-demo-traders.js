// ─── Seed ────────────────────────────────────────────────────────────────────

async function seed(client) {
  await client.query(`SET LOCAL app.current_user_role = 'SUPER_ADMIN'`);

  const traderProfileIds = [];

  for (const t of TRADERS) {
    // Idempotent: skip if user already exists
    const existing = await client.query(
      `SELECT id FROM users WHERE email = $1`,
      [t.email],
    );
    if (existing.rowCount > 0) {
      console.log(`  Skip (exists): ${t.email}`);
      const profileRes = await client.query(
        `SELECT id FROM trader_profiles WHERE user_id = $1`,
        [existing.rows[0].id],
      );
      if (profileRes.rowCount > 0) traderProfileIds.push(profileRes.rows[0].id);
      continue;
    }

    // 1. users
    const userRes = await client.query(
      `INSERT INTO users (email, password_hash, first_name, last_name, role, status, phone, phone_verified, email_verified)
       VALUES ($1, $2, $3, $4, 'TRADER', $5::user_status, $6, TRUE, FALSE)
       RETURNING id`,
      [t.email, DEMO_PASSWORD_HASH, t.first_name, t.last_name, t.status, t.phone],
    );
    const userId = userRes.rows[0].id;

    // 2. trader_profiles (trader_code auto-generated by trigger when passed empty string)
    const profileRes = await client.query(
      `INSERT INTO trader_profiles
         (user_id, trader_code, company_name, whatsapp_number, city, state,
          kyc_status, business_type, subscription_tier)
       VALUES ($1, '', $2, $3, $4, $5, $6::kyc_status, $7::business_type, $8::subscription_tier)
       RETURNING id, trader_code`,
      [
        userId, t.company_name, t.phone, t.city, t.state,
        t.kyc_status, t.business_type, t.subscription_tier,
      ],
    );
    const profileId = profileRes.rows[0].id;
    traderProfileIds.push(profileId);

    // 3. company_gstins
    await client.query(
      `INSERT INTO company_gstins (trader_profile_id, gstin, is_primary)
       VALUES ($1, $2, TRUE)`,
      [profileId, t.gstin],
    );

    console.log(`  Created: ${t.first_name} ${t.last_name} — ${t.company_name} (${profileRes.rows[0].trader_code})`);
  }

  // ─── Listings ─────────────────────────────────────────────────────────────
  // Only create listings if active products exist in the catalog.

  const prodRes = await client.query(
    `SELECT p.id, p.category_id, p.brand_id,
            v.id AS variant_id
     FROM products p
     JOIN product_variants v ON v.product_id = p.id AND v.is_active = TRUE
     WHERE p.status = 'ACTIVE'
     ORDER BY p.created_at
     LIMIT 6`,
  );

  if (prodRes.rowCount === 0) {
    console.log('\n  No active products found — skipping listings.');
    console.log('  Run: node scripts/seed-apple-iphones.js  to seed products first.');
    return;
  }

  // Check if listings already exist for demo traders to stay idempotent
  if (traderProfileIds.length === 0) return;
  const existingListings = await client.query(
    `SELECT 1 FROM listings WHERE trader_profile_id = ANY($1) LIMIT 1`,
    [traderProfileIds],
  );
  if (existingListings.rowCount > 0) {
    console.log('\n  Listings already exist — skipping.');
    return;
  }

  const listingFixtures = [
    { intent: 'WTS', stock_type: 'MASTER_CARTON', qty: 500, price: 65000, city: 'Mumbai', state: 'Maharashtra', traderIdx: 0, prodIdx: 0 },
    { intent: 'WTS', stock_type: 'LOOSE_ACTIVATED', qty: 200, price: 67500, city: 'Bengaluru', traderIdx: 2, state: 'Karnataka', prodIdx: 1 },
    { intent: 'WTB', stock_type: 'MASTER_CARTON', qty: 300, price: null,   city: 'New Delhi', traderIdx: 1, state: 'Delhi',       prodIdx: 2 },
    { intent: 'WTS', stock_type: 'MASTER_CARTON', qty: 100, price: 72000, city: 'Mumbai', state: 'Maharashtra', traderIdx: 0, prodIdx: 3 },
    { intent: 'WTB', stock_type: 'LOOSE_NON_ACTIVATED', qty: 50, price: null, city: 'New Delhi', traderIdx: 3, state: 'Delhi', prodIdx: 4 },
  ];

  let listingCount = 0;
  for (const f of listingFixtures) {
    const traderProfileId = traderProfileIds[f.traderIdx];
    if (!traderProfileId) continue;
    const prod = prodRes.rows[Math.min(f.prodIdx, prodRes.rowCount - 1)];

    await client.query(
      `INSERT INTO listings
         (listing_code, trader_profile_id, intent, product_id, variant_id,
          category_id, brand_id, stock_type, quantity, price_per_unit,
          city, state, status)
       VALUES ('', $1, $2::listing_intent, $3, $4, $5, $6, $7::listing_stock_type,
               $8, $9, $10, $11, 'ACTIVE')`,
      [
        traderProfileId, f.intent, prod.id, prod.variant_id,
        prod.category_id, prod.brand_id, f.stock_type,
        f.qty, f.price, f.city, f.state,
      ],
    );
    listingCount++;
  }
  console.log(`\n  Created ${listingCount} demo listings.`);
}

// ─── Undo ─────────────────────────────────────────────────────────────────────

async function undo(client) {
  await client.query(`SET LOCAL app.current_user_role = 'SUPER_ADMIN'`);

  const emails = TRADERS.map(t => t.email);

  // CASCADE on users → trader_profiles → listings
  const del = await client.query(
    `DELETE FROM users WHERE email = ANY($1) RETURNING email`,
    [emails],
  );
  console.log(`  Deleted ${del.rowCount} user(s): ${del.rows.map(r => r.email).join(', ')}`);
}

// ─── Main ─────────────────────────────────────────────────────────────────────

(async () => {
  if (!DB) {
    console.error('ELEX_CONNECTION_STRING is not set in .env');
    process.exit(1);
  }

  const client = new Client({ connectionString: DB });
  await client.connect();
  try {
    await client.query('BEGIN');

    if (UNDO) {
      console.log('\n⏪  Removing demo traders...');
      await undo(client);
    } else {
      console.log('\n🌱  Seeding 4 demo traders...');
      await seed(client);
    }

    await client.query('COMMIT');
    console.log(UNDO ? '\n✅  Undo complete.' : '\n✅  Seed complete.');
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('\n❌  Failed — rolled back:', err.message);
    process.exit(1);
  } finally {
    await client.end();
  }
})();
