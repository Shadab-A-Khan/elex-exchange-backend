import { Injectable, BadRequestException, ForbiddenException, NotFoundException } from '@nestjs/common';
import { DatabaseService } from '../database/database.service';
import { CreateListingDto, ListingIntent, ListingCondition, SpecRegion } from './dto/listing.dto';

@Injectable()
export class ListingsService {
  constructor(private db: DatabaseService) {}

  async create(userId: string, role: string, dto: CreateListingDto) {
    if (dto.intent === ListingIntent.WTS && !dto.price_per_unit) {
      throw new BadRequestException('price_per_unit is required for WTS listings');
    }

    const client = await this.db.getClient();
    try {
      await client.query('BEGIN');
      // Set RLS context on this connection so listings_insert_policy passes
      await client.query(`SELECT set_config('app.current_user_id', $1, true)`, [userId]);
      await client.query(`SELECT set_config('app.current_user_role', $1, true)`, [role]);

      const profileRes = await client.query(
        `SELECT id FROM trader_profiles WHERE user_id = $1 LIMIT 1`,
        [userId],
      );
      if (!profileRes.rows.length) {
        throw new ForbiddenException('Trader profile not found for this user');
      }
      const traderProfileId: string = profileRes.rows[0].id;

      // listing_code generated by BEFORE INSERT trigger; status defaults to ACTIVE
      const res = await client.query(
        `INSERT INTO listings
           (trader_profile_id, intent, product_name,
            quantity, price_per_unit, currency, condition, spec_region, description)
         VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9)
         RETURNING
           id, listing_code, intent, product_name, quantity,
           price_per_unit, currency, condition, spec_region,
           description, status, expires_at, created_at`,
        [
          traderProfileId,
          dto.intent,
          dto.product_name,
          dto.quantity,
          dto.price_per_unit ?? null,
          dto.currency,
          dto.condition    ?? null,
          dto.spec_region  ?? null,
          dto.description  ?? null,
        ],
      );

      await client.query('COMMIT');
      return res.rows[0];
    } catch (err) {
      await client.query('ROLLBACK');
      throw err;
    } finally {
      client.release();
    }
  }

  async findAll(
    intent?: string,
    condition?: string,
    spec_region?: string,
    price_min?: number,
    price_max?: number,
    search?: string,
    limit = 50,
    offset = 0,
  ) {
    const params: any[] = [];
    const whereClauses: string[] = [
      `l.status = 'ACTIVE'`,
      `l.expires_at > NOW()`,
    ];

    if (intent === ListingIntent.WTS || intent === ListingIntent.WTB) {
      params.push(intent);
      whereClauses.push(`l.intent = $${params.length}`);
    }

    if (condition) {
      const valid = Object.values(ListingCondition) as string[];
      const vals = condition.split(',').map((v) => v.trim()).filter((v) => valid.includes(v));
      if (vals.length !== condition.split(',').filter(Boolean).length) {
        throw new BadRequestException(
          `condition must be one or more of: ${valid.join(', ')}`,
        );
      }
      if (vals.length) {
        const placeholders = vals.map((v) => { params.push(v); return `$${params.length}`; });
        whereClauses.push(`l.condition = ANY(ARRAY[${placeholders.join(',')}])`);
      }
    }

    if (spec_region) {
      const valid = Object.values(SpecRegion) as string[];
      const vals = spec_region.split(',').map((v) => v.trim()).filter((v) => valid.includes(v));
      if (vals.length !== spec_region.split(',').filter(Boolean).length) {
        throw new BadRequestException(
          `spec_region must be one or more of: ${valid.join(', ')}`,
        );
      }
      if (vals.length) {
        const placeholders = vals.map((v) => { params.push(v); return `$${params.length}`; });
        whereClauses.push(`l.spec_region = ANY(ARRAY[${placeholders.join(',')}])`);
      }
    }

    if (price_min != null && !isNaN(price_min)) {
      params.push(price_min);
      whereClauses.push(`l.price_per_unit >= $${params.length}`);
    }

    if (price_max != null && !isNaN(price_max)) {
      params.push(price_max);
      whereClauses.push(`l.price_per_unit <= $${params.length}`);
    }

    if (search) {
      params.push(`%${search}%`);
      whereClauses.push(`l.product_name ILIKE $${params.length}`);
    }

    params.push(limit, offset);

    const res = await this.db.query(
      `SELECT
         l.id, l.listing_code, l.intent, l.product_name,
         l.quantity, l.price_per_unit, l.currency,
         l.condition, l.spec_region, l.description,
         l.status, l.expires_at, l.created_at,
         tp.company_name AS trader,
         tp.trader_code,
         tp.whatsapp_number AS phone,
         tp.city,
         tp.kyc_status
       FROM listings l
       JOIN trader_profiles tp ON tp.id = l.trader_profile_id
       WHERE ${whereClauses.join(' AND ')}
       ORDER BY l.created_at DESC
       LIMIT $${params.length - 1} OFFSET $${params.length}`,
      params,
    );
    return res.rows;
  }

  async findOne(id: string) {
    const res = await this.db.query(
      `SELECT
         l.id, l.listing_code, l.intent, l.product_name,
         l.quantity, l.price_per_unit, l.currency,
         l.condition, l.spec_region, l.description,
         l.status, l.expires_at, l.created_at,
         tp.company_name AS trader,
         tp.trader_code,
         tp.whatsapp_number AS phone,
         tp.city,
         tp.kyc_status
       FROM listings l
       JOIN trader_profiles tp ON tp.id = l.trader_profile_id
       WHERE (l.id::text = $1 OR l.listing_code = $1)
         AND l.status = 'ACTIVE' AND l.expires_at > NOW()`,
      [id],
    );
    if (!res.rows.length) throw new NotFoundException('Listing not found');
    return res.rows[0];
  }
}
